export function clinicalText(
  language: ClinicalLanguage,
  value: string
) {
  return language === "fr"
    ? french[value] ?? value
    : value;
}

export function clinicalLocale(
  language: ClinicalLanguage
) {
  return language === "fr"
    ? "fr-CM"
    : "en-CM";
}

export function orderStatusConfirmation(
  language: ClinicalLanguage,
  status: string,
  orderName: string
) {
  if (language === "fr") {
    switch (status) {
      case "Discontinued":
        return `Arrêter « ${orderName} » ?`;
      case "Held":
        return `Suspendre « ${orderName} » ?`;
      case "Completed":
        return `Marquer « ${orderName} » comme terminé ?`;
      default:
        return `Reprendre « ${orderName} » ?`;
    }
  }

  switch (status) {
    case "Discontinued":
      return `Discontinue "${orderName}"?`;
    case "Held":
      return `Place "${orderName}" on hold?`;
    case "Completed":
      return `Mark "${orderName}" completed?`;
    default:
      return `Resume "${orderName}"?`;
  }
}


export function immunizationStatusLabel(
  language: ClinicalLanguage,
  value: string
) {
  if (language !== "fr") {
    return value;
  }

  switch (value) {
    case "Completed":
      return "Effectuée";
    case "Due":
      return "À faire";
    case "Declined":
      return "Refusée";
    case "Contraindicated":
      return "Contre-indiquée";
    default:
      return clinicalText(
        language,
        value
      );
  }
}
